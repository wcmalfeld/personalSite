// ---------- redirects, feed, sitemap ----------
export function redirectPage(site, fromPath, toPath) {
  const depth = fromPath.split('/').length - 1;
  const rel = '../'.repeat(depth) + toPath;
  return `<!DOCTYPE html>
${GENERATED}
<html lang="en">
<head>
<meta charset="UTF-8">
<title>Moved</title>
<meta name="robots" content="noindex">
<link rel="canonical" href="${a(`${site.siteUrl}/${toPath}`)}">
<meta http-equiv="refresh" content="0; url=${a(rel)}">
<script>location.replace(${JSON.stringify(rel)} + location.hash);</script>
</head>
<body>
<p>This page has moved to <a href="${a(rel)}">${a(`${site.siteUrl}/${toPath}`)}</a>.</p>
</body>
</html>
`;
}

const xml = (s) => t(s).replace(/"/g, '&quot;');

export function feed(site, articles) {
  const items = articles.slice(0, 30).map((x) => `  <item>
    <title>${xml(x.title)}</title>
    <link>${site.siteUrl}/writing/${x.slug}/</link>
    <guid isPermaLink="true">${site.siteUrl}/writing/${x.slug}/</guid>
    <pubDate>${x.date.toUTCString()}</pubDate>
    <category>${xml(x.category.name)}</category>
    <description>${xml(x.excerpt)}</description>
  </item>`).join('\n');
  return `<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom">
<channel>
  <title>${xml(site.publication.title)} — ${xml(site.author)}</title>
  <link>${site.siteUrl}/writing/</link>
  <description>${xml(site.publication.description)}</description>
  <language>en-us</language>
  <atom:link href="${site.siteUrl}/writing/feed.xml" rel="self" type="application/rss+xml"/>
${articles.length ? `  <lastBuildDate>${articles[0].date.toUTCString()}</lastBuildDate>\n` : ''}${items}
</channel>
</rss>
`;
}

export function sitemap(site, articles) {
  const urls = [
    { loc: `${site.siteUrl}/` },
    { loc: `${site.siteUrl}/writing/`, lastmod: articles[0] && iso(articles[0].updated || articles[0].date) },
    ...articles.map((x) => ({ loc: `${site.siteUrl}/writing/${x.slug}/`, lastmod: iso(x.updated || x.date) })),
  ];
  return `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.map((u) => `  <url><loc>${xml(u.loc)}</loc>${u.lastmod ? `<lastmod>${u.lastmod}</lastmod>` : ''}</url>`).join('\n')}
</urlset>
`;
}

export function robots(site) {
  return `User-agent: *\nAllow: /\n\nSitemap: ${site.siteUrl}/sitemap.xml\n`;
}
