const GENERATED = '<!-- Generated by scripts/writing/build.mjs from content/writing/. Edit the Markdown, not this file. -->';

const fmtDate = (d, month = 'long') => d.toLocaleDateString('en-US', { year: 'numeric', month, day: 'numeric', timeZone: 'UTC' });
const iso = (d) => d.toISOString().slice(0, 10);
const enc = (p) => p.split('/').map(encodeURIComponent).join('/');

export const imgUrl = (img, root) => (img.external ? img.external : root + enc(img.path));
const absUrl = (site, img) => (img.external ? img.external : `${site.siteUrl}/${enc(img.path)}`);

// ---------- shared chrome ----------
function nav(root, active) {
  const link = (href, label, key) => {
    const on = active === key || active === `${key}:page`;
    return `<li><a href="${href}"${on ? ' class="active"' : ''}${active === `${key}:page` ? ' aria-current="page"' : ''}>${label}</a></li>`;
  };
  return `<nav class="site-nav" aria-label="Main">
  <div class="wrap">
    <a href="${root}" class="brand">Will<span>.</span>Malfeld</a>
    <ul class="nav-links">
      ${link(root, 'About', 'about')}
      ${link(`${root}writing/`, 'Writing', 'writing')}
      <li><a href="mailto:${a(SITE.contact.email)}">Contact</a></li>
    </ul>
  </div>
</nav>`;
}

