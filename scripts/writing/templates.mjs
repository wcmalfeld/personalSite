let SITE = null;

function page({ root, path, title, ogTitle, description, ogType = 'website', image, imageAlt, extraHead = '', bodyClass = '', active = 'writing', content, script = true }) {
  const canonical = `${SITE.siteUrl}/${path.replace(/index\.html$/, '')}`;
  const shareImage = image && !image.missing && /\.(jpe?g|png|webp|gif)$/i.test(image.external || image.path) ? image : SITE.shareImage;
  return `<!DOCTYPE html>
${GENERATED}
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>${t(title)}</title>
<meta name="description" content="${a(description)}">
<link rel="canonical" href="${a(canonical)}">
<meta property="og:site_name" content="${a(SITE.author)}">
<meta property="og:type" content="${ogType}">
<meta property="og:title" content="${a(ogTitle || title)}">
<meta property="og:description" content="${a(description)}">
<meta property="og:url" content="${a(canonical)}">
<meta property="og:image" content="${a(absUrl(SITE, shareImage))}">
<meta property="og:image:alt" content="${a(shareImage === image ? imageAlt || '' : SITE.author)}">
<meta name="twitter:card" content="summary_large_image">
<link rel="alternate" type="application/rss+xml" title="${a(SITE.publication.title)} — ${a(SITE.author)}" href="${root}writing/feed.xml">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="${FONTS}" rel="stylesheet">
<link rel="stylesheet" href="${root}css/style.css">
<link rel="stylesheet" href="${root}css/writing.css">
${extraHead}</head>
<body class="fn${bodyClass ? ` ${bodyClass}` : ''}">
<a class="skip-link" href="#main">Skip to content</a>
${nav(root, active)}
<main id="main">
${content}
</main>
${footer(root)}
${script ? `<script src="${root}js/writing.js" defer></script>\n` : ''}</body>
</html>
`;
}

// ---------- pieces ----------
function meta(article, { long = false } = {}) {
  return `<time datetime="${iso(article.date)}">${fmtDate(article.date, long ? 'long' : 'short')}</time><span class="sep" aria-hidden="true">&middot;</span>${article.readingMinutes} min read`;
}

function picture(img, root, alt, { eager = false, position = '', cls = '' } = {}) {
  if (!img || img.missing) return missingImage({ alt }, '');
  const dims = img.width && img.height ? ` width="${img.width}" height="${img.height}"` : '';
  const load = eager ? ' fetchpriority="high"' : ' loading="lazy"';
  const style = position ? ` style="object-position:${a(position)}"` : '';
  return `<img${cls ? ` class="${cls}"` : ''} src="${a(imgUrl(img, root))}" alt="${a(alt)}"${dims}${load} decoding="async"${style}>`;
}

function searchText(article) {
  return [article.title, article.subtitle, article.excerpt, article.category.name, ...article.tags].join(' ').toLowerCase();
}

export function card(article, root, { variant = article.card, hidden = false, featuredCopy = false } = {}) {
  const href = `${root}writing/${article.slug}/`;
  const hasCover = article.cover && !article.cover.missing;
  if (!article.cover) variant = 'text';
  let media = '';
  if (variant !== 'text') {
    const extras = variant === 'wide' || variant === 'photo' ? article.cardImages.slice(0, 2) : [];
    if (extras.length) {
      media = `<div class="card-media card-media--collage card-media--n${extras.length + 1}">
        ${picture(article.cover, root, article.coverAlt, { position: article.coverPosition })}
        ${extras.map((img) => picture(img, root, '')).join('\n        ')}
      </div>`;
    } else {
      media = `<div class="card-media${hasCover ? '' : ' card-media--missing'}">${picture(article.cover, root, article.coverAlt, { position: article.coverPosition })}</div>`;
    }
  }
  return `<article class="card card--${variant}" data-topic="${a(article.category.slug)}" data-search="${a(searchText(article))}"${featuredCopy ? ' data-featured-copy' : ''}${hidden ? ' hidden' : ''}>
      ${media}
      <div class="card-text">
        <p class="kicker">${article.draft ? '<span class="kicker-flag">Draft</span>' : ''}${t(article.category.name)}</p>
        <h3 class="card-title"><a class="card-link" href="${href}">${t(article.title)}</a></h3>
        <p class="card-excerpt">${t(article.excerpt)}</p>
        <p class="meta">${meta(article)}</p>
      </div>
    </article>`;
}

// ---------- landing page ----------
export function landingPage(site, articles) {
  SITE = site;
  const root = '../';
  const pub = site.publication;
  const featured = articles.find((x) => x.featured) || articles[0];
  const rest = articles.filter((x) => x !== featured);
  const used = site.categories.filter((c) => articles.some((x) => x.category.slug === c.slug));

  const featuredHtml = featured ? `
<section class="fn-featured" aria-labelledby="featured-title">
  <div class="wrap">
    <article class="feature${featured.cover ? '' : ' feature--text'}">
      ${featured.cover ? `<a class="feature-media" href="${featured.slug}/" tabindex="-1" aria-hidden="true">${picture(featured.cover, root, featured.coverAlt, { eager: true, position: featured.coverPosition })}</a>` : ''}
      <div class="feature-text">
        <p class="kicker"><span class="kicker-flag">Featured</span>${t(featured.category.name)}</p>
        <h2 class="feature-title" id="featured-title"><a href="${featured.slug}/">${t(featured.title)}</a></h2>
        ${featured.subtitle ? `<p class="feature-sub">${t(featured.subtitle)}</p>` : ''}
        <p class="feature-excerpt">${t(featured.excerpt)}</p>
        <p class="meta">${meta(featured, { long: true })}</p>
        <a class="read-link" href="${featured.slug}/">Read the essay <span aria-hidden="true">&rarr;</span><span class="visually-hidden">: ${t(featured.title)}</span></a>
      </div>
    </article>
  </div>
</section>` : '';

  const cards = [
    ...(featured ? [card(featured, root, { variant: featured.cover ? 'standard' : 'text', hidden: true, featuredCopy: true })] : []),
    ...rest.map((x) => card(x, root)),
  ].join('\n    ');

  const archive = articles.length > 12 ? `
<section class="fn-archive" aria-labelledby="archive-title">
  <div class="wrap">
    <h2 class="fn-label" id="archive-title">Index</h2>
    <ol class="archive-list">
      ${articles.map((x) => `<li><a href="${x.slug}/"><span class="archive-title">${t(x.title)}</span><span class="archive-cat">${t(x.category.name)}</span><time datetime="${iso(x.date)}">${fmtDate(x.date, 'short')}</time></a></li>`).join('\n      ')}
    </ol>
  </div>
</section>` : '';

  const content = `
<header class="fn-masthead">
  ${CONTOURS}
  <div class="wrap">
    <p class="eyebrow">${t(pub.eyebrow)}</p>
    <h1 class="fn-title">${t(pub.title)}</h1>
    <div class="fn-intro">
      <p>${t(pub.intro)}</p>
      <p class="fn-kinds">Essays <span aria-hidden="true">&middot;</span> Stories <span aria-hidden="true">&middot;</span> Observations <span aria-hidden="true">&middot;</span> Ideas</p>
    </div>
  </div>
</header>
${featuredHtml}
<section class="fn-collection" aria-labelledby="collection-title">
  <div class="wrap">
    <div class="fn-toolbar">
      <h2 class="fn-label" id="collection-title">${featured && rest.length ? 'More writing' : 'All writing'}</h2>
      <div class="fn-controls" data-controls hidden>
        <div class="fn-filters" role="group" aria-label="Filter by topic">
          <button type="button" class="chip" data-topic="" aria-pressed="true">All Writing <span class="chip-n">${articles.length}</span></button>
          ${used.map((c) => `<button type="button" class="chip" data-topic="${a(c.slug)}" aria-pressed="false">${t(c.name)} <span class="chip-n">${articles.filter((x) => x.category.slug === c.slug).length}</span></button>`).join('\n          ')}
        </div>
        <div class="fn-search">
          <label class="visually-hidden" for="fn-q">Search writing</label>
          <svg aria-hidden="true" viewBox="0 0 20 20" width="16" height="16"><circle cx="8.5" cy="8.5" r="5.5" fill="none" stroke="currentColor" stroke-width="1.6"/><path d="M13 13l4.5 4.5" stroke="currentColor" stroke-width="1.6" stroke-linecap="round"/></svg>
          <input type="search" id="fn-q" placeholder="Search titles, topics, tags" autocomplete="off">
        </div>
      </div>
    </div>
    <p class="fn-status visually-hidden" role="status" aria-live="polite"></p>
    <div class="fn-grid" data-grid>
    ${cards}
    </div>
    <div class="fn-empty" data-empty hidden>
      <p class="fn-empty-title">Nothing here yet.</p>
      <p>No writing matches <span data-empty-desc>that search</span>.</p>
      <button type="button" class="chip" data-reset>Show all writing</button>
    </div>
  </div>
</section>
${archive}`;

  return page({
    root,
    path: 'writing/',
    title: `${pub.title} — ${site.author}`,
    description: pub.description,
    content,
    active: 'writing:page',
    bodyClass: 'fn-landing',
  });
}

// ---------- article page ----------
export function articlePage(site, article, related) {
  SITE = site;
  const root = '../../';
  const portrait = article.cover && article.cover.height > article.cover.width;
  const hero = article.cover ? `
  <figure class="essay-hero${portrait ? ' essay-hero--portrait' : ''}">
    ${article.cover.missing ? missingImage({ alt: article.coverAlt }, '3 / 2') : picture(article.cover, root, article.coverAlt, { eager: true })}
    ${article.coverCaption || article.coverCredit ? `<figcaption>${article.coverCaption ? `<span class="cap">${t(article.coverCaption)}</span>` : ''}${article.coverCredit ? ` <span class="credit">${t(article.coverCredit)}</span>` : ''}</figcaption>` : ''}
  </figure>` : '';

  const jsonLd = {
    '@context': 'https://schema.org',
    '@type': 'BlogPosting',
    headline: article.title,
    description: article.seoDescription,
    datePublished: iso(article.date),
    dateModified: iso(article.updated || article.date),
    author: { '@type': 'Person', name: site.author, url: `${site.siteUrl}/` },
    mainEntityOfPage: `${site.siteUrl}/writing/${article.slug}/`,
    ...(article.cover && !article.cover.missing && /\.(jpe?g|png|webp|gif)$/i.test(article.cover.external || article.cover.path) ? { image: absUrl(site, article.cover) } : {}),
    articleSection: article.category.name,
    keywords: article.tags.join(', '),
  };

  const draftBanner = article.draft ? '<p class="draft-banner" role="note">Draft preview — this piece is not published and will not appear on the live site.</p>' : '';

  const content = `${draftBanner}
<article class="essay">
  <header class="essay-head">
    <a class="back-link" href="../"><span aria-hidden="true">&larr;</span> ${t(site.publication.title)}</a>
    <p class="eyebrow"><a href="../?topic=${a(article.category.slug)}">${t(article.category.name)}</a></p>
    <h1 class="essay-title">${t(article.title)}</h1>
    ${article.subtitle ? `<p class="essay-sub">${t(article.subtitle)}</p>` : ''}
    <p class="meta essay-meta">By <a href="${root}">${t(article.author)}</a><span class="sep" aria-hidden="true">&middot;</span>${meta(article, { long: true })}</p>
  </header>
  ${hero}
  <div class="prose">
${article.html}
  </div>
  <footer class="essay-end">
    <span class="end-mark" aria-hidden="true"></span>
    ${article.tags.length ? `<ul class="essay-tags" aria-label="Tags">${article.tags.map((tag) => `<li><a href="../?q=${encodeURIComponent(tag)}">${t(tag)}</a></li>`).join('')}</ul>` : ''}
    <div class="author-card">
      <img class="author-photo" src="${root}${a(site.authorImage)}" alt="" width="64" height="64" loading="lazy">
      <div>
        <p class="author-name">${t(site.author)}</p>
        <p class="author-role">${t(site.authorRole)}</p>
        <a class="author-more" href="${root}">More about me <span aria-hidden="true">&rarr;</span></a>
      </div>
    </div>
  </footer>
</article>
${related.length ? `
<section class="related" aria-labelledby="related-title">
  <div class="wrap">
    <h2 class="fn-label" id="related-title">Keep reading</h2>
    <div class="fn-grid fn-grid--related">
    ${related.map((x) => card(x, root, { variant: x.cover ? 'standard' : 'text' })).join('\n    ')}
    </div>
    <p class="related-links"><a href="../"><span aria-hidden="true">&larr;</span> All writing</a><a href="${root}">About Will <span aria-hidden="true">&rarr;</span></a></p>
  </div>
</section>` : ''}`;

  return page({
    root,
    path: `writing/${article.slug}/`,
    title: `${article.seoTitle} — ${site.author}`,
    ogTitle: article.seoTitle,
    description: article.seoDescription,
    ogType: 'article',
    image: article.shareImage || (article.cover && !article.cover.missing ? article.cover : null),
    imageAlt: article.coverAlt,
    extraHead: `<meta property="article:published_time" content="${iso(article.date)}">
<meta property="article:section" content="${a(article.category.name)}">
${article.draft ? '<meta name="robots" content="noindex">\n' : ''}<script type="application/ld+json">${JSON.stringify(jsonLd).replace(/</g, '\\u003c')}</script>
`,
    bodyClass: 'fn-article',
    content,
  });
}

